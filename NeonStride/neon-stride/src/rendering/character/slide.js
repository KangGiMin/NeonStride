export function drawSlide(scene, y, shadow, p) {
  scene.line(
    [p(-0.48, 0.1), p(0.1, 0.18), p(0.3, 0.25)],
    "#244353",
    shadow.k * 0.15,
  );
  scene.line(
    [p(-0.1, 0.2), p(0.5, 0.23), p(0.75, 0.08)],
    "#172a3d",
    shadow.k * 0.16,
  );
  scene.box(
    0,
    y + 0.2,
    -0.05,
    0.55,
    0.35,
    0.65,
    ["#263c4d", "#172a3a", "#52707a"],
    "#91cad077",
  );
  scene.box(
    0.02,
    y + 0.29,
    0.45,
    0.3,
    0.29,
    0.3,
    ["#213b50", "#1a2c40", "#688187"],
    "#89cfd599",
  );
  scene.line([p(-0.25, 0.28, -0.15), p(-0.55, 0.15, -0.35)], "#b4ff79", 2, 8);
}
